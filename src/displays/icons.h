// ==========================================================================
// icons.h — Icon glyphs extracted from the classic glcdfont
// ==========================================================================
// Scale 1: 8 rows of 6 bits, uint8_t, bit 5 = leftmost pixel (col 0).
// Scale N (2..5): 8*N rows of 6*N bits, uint32_t, bit 6*N-1 = leftmost.
//  @ = pixel ON    . = pixel OFF
// A mark is drawn at the cell's own size: 6*textsize x 8*textsize px.
// iconAt() picks the largest hand-drawn scale that divides the request, else
// scale 1 blown up.  The ICON_TABLES block at the end is generated by
// src/displays/tools/icons_tool.py; everything above it is hand-authored.
// ==========================================================================


