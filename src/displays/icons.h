// The bit table for cp at scale k, or NULL.  k is 1..5: scale 1 is the uint8_t
// set, every variant is uint32_t.  A switch rather than an array of table
// pointers because uint8_t* const* does not convert to void* const*.
static inline const void* iconBits(uint8_t cp, uint8_t k) {
  switch (k) {
    case 5:  return (const void*)pgm_read_ptr(&ICON_TABLE_5[cp]);
    case 4:  return (const void*)pgm_read_ptr(&ICON_TABLE_4[cp]);
    case 3:  return (const void*)pgm_read_ptr(&ICON_TABLE_3[cp]);
    case 2:  return (const void*)pgm_read_ptr(&ICON_TABLE_2[cp]);
    default: return (const void*)pgm_read_ptr(&ICON_TABLE[cp]);
  }
}

// What to draw for cp at request scale want: the largest existing divisor of
// want, the request itself included, else 1.  ps = want / k is the renderer's
// integer pixel factor, so a mark drawn AT the request size is drawn 1:1.
// A scale above 5 has no table, so it lands on 1 with ps = want - the blow-up.
struct IconSel { const void* bits; uint8_t scale; };
static inline IconSel iconAt(uint8_t cp, uint8_t want) {
  if (want < 2) return IconSel{ iconBits(cp, 1), 1 };
  const uint8_t top = (uint8_t)((want < 5) ? want : 5);
  for (uint8_t k = top; k > 1; k--)
    if (want % k == 0) {
      const void* b = iconBits(cp, k);
      if (b) return IconSel{ b, k };
    }
  return IconSel{ iconBits(cp, 1), 1 };
}
