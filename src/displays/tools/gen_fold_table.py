BMP = (0x0080, 0xFFFF)


def canonical_base(ch):
    """Base codepoint after stripping combining marks, or None."""
    decomposed = unicodedata.normalize("NFD", ch)
    base = "".join(c for c in decomposed if unicodedata.category(c) != "Mn")
    if len(base) == 1 and base != ch:
        return ord(base)
    return None


def nfkd_stripped(ch):
    """Compatibility decomposition with combining marks removed."""
    return [c for c in unicodedata.normalize("NFKD", ch)
            if unicodedata.category(c) != "Mn"]


def name_lookalike(ch):
    """ASCII stand-in for a Greek or Cyrillic letter, from its Unicode name."""
    name = unicodedata.name(ch, "")
    if not name.startswith(("GREEK ", "CYRILLIC ")):
        return None
    upper = " CAPITAL LETTER " in name
    marker = " CAPITAL LETTER " if upper else " SMALL LETTER "
    if marker not in name:
        return None
    letter = name.split(marker, 1)[1]
    letter = letter.split(" WITH ", 1)[0].strip()
    ascii_ch = LETTER_OVERRIDES.get(letter)
    if ascii_ch is None:
        ascii_ch = letter[0]
    return ord(ascii_ch.upper() if upper else ascii_ch.lower())


def candidates(cp):
    """Steps for cp in order of preference.  ASCII first, because that ends the
    chain; a non-ASCII base may follow, but see build(): it is only used when the
    base itself resolves, which is what stops Hangul (whose Jamo bases lead
    nowhere) from costing 44 KB of flash for no benefit."""
    ch = chr(cp)
    out = []

    def add(value):
        if value is not None and value != cp and value not in out:
            out.append(value)

    add(OVERRIDES.get(cp))
    add(name_lookalike(ch))
    stripped = nfkd_stripped(ch)
    for c in stripped:
        if ord(c) < 0x80:
            add(ord(c))
            break
    add(canonical_base(ch))
    if stripped:
        add(ord(stripped[0]))
    return out


def skipped(cp):
    return any(lo <= cp <= hi for lo, hi in SKIP_RANGES)


def utf8_len(cp):
    if cp < 0x80:
        return 1
    if cp < 0x800:
        return 2
    if cp < 0x10000:
        return 3
    return 4


def assert_byte_monotonic(entries):
    """Every step must fit in the bytes its codepoint came from.

    preTextString() rewrites a widget's string in place, which is only safe if
    no step grows: a two-byte codepoint may not step to a three-byte one, and no
    step may reach outside the BMP (the encoder writes three bytes at most).
    """
    bad = [(cp, nxt) for cp, nxt in entries.items()
           if utf8_len(nxt) > utf8_len(cp) or nxt > 0xFFFF]
    if bad:
        raise SystemExit(
            "steps that would grow the string (breaks in-place rewriting): %s%s"
            % (", ".join("U+%04X->U+%04X" % pair for pair in bad[:8]),
               " ..." if len(bad) > 8 else ""))

    # The table is emitted in two halves so both keep 4-byte entries: BMP keys
    # are the codepoint, plane-1 keys are the offset from 0x10000 (which fits a
    # uint16).  Anything above plane 1 would need a wider key - fail loudly
    # rather than truncate silently.
    high = [cp for cp in entries if cp > 0x1FFFF]
    if high:
        raise SystemExit("astral keys above plane 1 not supported: %s"
                         % ", ".join("U+%05X" % cp for cp in high[:8]))


def scan_codepoints():
    for lo, hi in [BMP] + SUPPLEMENTARY_RANGES:
        for cp in range(lo, hi + 1):
            if not skipped(cp):
                yield cp


def build():
    """Two phases: ASCII steps first, then non-ASCII bases that can progress.

    A non-ASCII base is only accepted once it is itself a key in the table or is
    ASCII, because otherwise the step is a dead end.  Without that guard the
    11,172 Hangul syllables each claim a Jamo base that leads nowhere - 44 KB of
    flash for no benefit - while the mathematical Greek letters keep their step
    to plain Greek, which does resolve.
    """
    cand = {}
    for cp in scan_codepoints():
        steps = candidates(cp)
        if steps:
            cand[cp] = steps

    entries = {}
    for cp, steps in cand.items():
        for value in steps:
            if value < 0x80:
                entries[cp] = value
                break

    for _ in range(4):  # chains are at most a few steps long
        added = 0
        for cp, steps in cand.items():
            if cp in entries:
                continue
            for value in steps:
                if value in entries:
                    entries[cp] = value
                    added += 1
                    break
        if not added:
            break

    assert_byte_monotonic(entries)
    return entries


def emit(entries):
    keys = sorted(entries)
    assert len(keys) == len(set(keys)), "duplicate codepoints in table"

    lines = []
    lines.append("// Generated by gen_fold_table.py - do not edit by hand.")
    lines.append("//")
    lines.append("// One step of the preText() fallback chain: walk this table, re-testing")
    lines.append("// the font after each step, and stop at the first codepoint the font can")
    lines.append("// draw.  Entries MUST stay in ascending codepoint order - the lookup is a")
    lines.append("// binary search and an out-of-order entry would silently miss.  The")
    lines.append("// generator emits sorted output and asserts uniqueness, so re-run it rather")
    lines.append("// than editing a codepoint here by hand.")
    lines.append("//")
    lines.append("// %d entries in two halves (%d bytes; GFXglyph is 8 bytes, for scale)."
                 % (len(keys), len(keys) * 4))
    lines.append("")
    lines.append("#ifndef pretext_fold_h")
    lines.append("#define pretext_fold_h")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("#include <Arduino.h>   // PROGMEM, pgm_read_word")
    lines.append("")
    lines.append("// Two halves, each with 4-byte entries.  The low half keys on the codepoint")
    lines.append("// itself; the high half keys on the offset from 0x10000, which fits a uint16")
    lines.append("// and keeps the entries narrow.  pretext.cpp picks by range.")
    lines.append("struct PreTextFoldStep {")
    lines.append("  uint16_t key;   // codepoint, or offset from 0x10000 in the high half")
    lines.append("  uint16_t next;  // the step to try before giving up on it")
    lines.append("};")
    lines.append("")

    def emit_half(name, rows, show_blocks):
        lines.append("const PreTextFoldStep %s[] PROGMEM = {" % name)
        row = []
        current_block = None
        for key, value, block in rows:
            if show_blocks and block != current_block:
                if row:
                    lines.append("  " + " ".join(row))
                    row = []
                lines.append("  /* %s */" % block)
                current_block = block
            row.append("{0x%04X, 0x%04X},/* %s */" % (key, value, comment_for(value)))
            if len(row) == 4:
                lines.append("  " + " ".join(row))
                row = []
        if row:
            lines.append("  " + " ".join(row))
        lines.append("};")
        lines.append("")

    low = [(cp, entries[cp], block_name(cp)) for cp in keys if cp <= 0xFFFF]
    high = [(cp - 0x10000, entries[cp], block_name(cp)) for cp in keys if cp > 0xFFFF]

    emit_half("preTextFoldTable", low, True)
    emit_half("preTextFoldTableHigh", high, False)

    lines.append("#define PRETEXT_FOLD_TABLE_LEN (sizeof(preTextFoldTable) / sizeof(preTextFoldTable[0]))")
    lines.append("#define PRETEXT_FOLD_TABLE_HIGH_LEN (sizeof(preTextFoldTableHigh) / sizeof(preTextFoldTableHigh[0]))")
    lines.append("#define PRETEXT_FOLD_HIGH_BASE 0x10000UL")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def comment_for(base):
    named = {
        0x20: "space", 0x21: "!", 0x22: '"', 0x25: "%", 0x27: "'", 0x2B: "+",
        0x2C: ",", 0x2D: "-", 0x2E: ".", 0x2F: "/", 0x3A: ":", 0x3C: "<",
        0x3D: "=", 0x3E: ">", 0x3F: "?", 0x5B: "[", 0x5D: "]", 0x5E: "^",
        0x7C: "|", 0x7E: "~",
    }
    if base in named:
        return named[base]
    if 0x20 <= base < 0x7F:
        return chr(base)
    return "U+%04X" % base


