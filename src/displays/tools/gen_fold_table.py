"""Generate pretext_fold.h - the stepping table for preText()'s fallback chain.

WHY THIS IS GENERATED
---------------------
preText() must degrade gracefully against ANY display font: a font that has the
glyph keeps it, a font that has a *nearer* representation gets that instead, and
only when nothing is available does the codepoint become a substitute.  That
needs a one-step mapping table walked as a chain, and the contents are Unicode
facts, so the table is generated (the fonts are generated by bdf2adafruit3.py in
the same spirit).  This file is the audit trail.

THE ONE RULE
------------
For each codepoint outside ASCII, the first of these that applies wins:

  1. OVERRIDES          - the hand-picked visual or transliteration choice, and
                          every place a decomposition would be wrong or would
                          lead somewhere silly.
  2. canonical base     - NFD, combining marks stripped.  Keeps the SAME script
                          where possible, so a font with Greek gets Greek:
                          U+1F00 -> U+03B1 (alpha), U+0450 -> U+0435 (ie).
  3. NFKD first ASCII   - the first ASCII character of the compatibility
                          decomposition.  This is what covers the "letter and
                          digit" forms without a hand-written table: fullwidth
                          (U+FF21 -> A), mathematical alphanumerics
                          (U+1D400 -> A), enclosed alphanumerics (U+2460 -> 1),
                          Roman numerals (U+216B -> X), number forms
                          (U+00BD -> 1), superscripts, presentation forms
                          (U+FB03 -> f), letterlike symbols (U+2116 -> N).
  4. name lookalike     - Greek and Cyrillic base letters have no decomposition
                          at all, so their ASCII stand-in comes from the letter
                          name: CYRILLIC SMALL LETTER DE -> d.

Note what the rule deliberately does NOT do: decorative symbols have no
decomposition, so U+263A and U+2713 fall through to the substitute instead of
being "translated" into punctuation.  That is the agreed policy, and it is
enforced by Unicode data rather than by a hand-maintained deny list.

Because steps 2/3/4 can land on a non-ASCII codepoint that is itself a key in
this table, preText() walks the table as a chain and re-tests the font after
every step.  That is what lets one table serve both a font with Greek and a font
without it: U+1F00 -> alpha (accepted by a Greek font) -> a (accepted by a Latin
font).

Run:  python src/displays/tools/gen_fold_table.py          (regenerate)
      python src/displays/tools/gen_fold_table.py --stats  (coverage report)
The generated header is committed; this script is a maintenance tool and is not
part of the build.
"""

