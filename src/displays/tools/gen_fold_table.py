def report_coverage(entries):
    print("mapping coverage (mapped codepoints / block size)")
    print("  a codepoint the active font carries is rendered as-is, so this shares")
    print("  the work with the font; the chain only walks where the font is lacking.")
    print()
    for lo, hi, name in COVERAGE_BLOCKS:
        n = sum(1 for cp in range(lo, hi + 1) if cp in entries)
        total = hi - lo + 1
        print("  %-33s %5d / %-6d %5.1f%%" % (name, n, total, 100.0 * n / total))
    bmp = sum(1 for cp in range(0x0080, 0x10000) if cp in entries)
    print()
    print("  %-33s %5d / %-6d %5.1f%%" % ("whole BMP (above ASCII)", bmp,
                                          0x10000 - 0x80,
                                          100.0 * bmp / (0x10000 - 0x80)))
    print()
    print("  Decorative symbols have no decomposition, so U+263A and U+2713 stay")
    print("  unmapped by construction and resolve to the substitute.")


